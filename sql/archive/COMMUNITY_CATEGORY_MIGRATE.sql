-- 커뮤니티 카테고리 마이그레이션 (멱등성 보장)
-- 구 카테고리 → 새 카테고리 매핑
--   스트레스 관리  → 스트레스
--   경험 공유     → 일상·기타
--   함께 해요     → 일상·기타
--   질문과 답변   → 일상·기타
--   추천 및 후기  → 일상·기타
--   우울          → 우울      (그대로)
--   불안          → 불안      (그대로)
--   인간관계      → 인간관계  (그대로)
--   전체 / 스트레스 / 일상·기타 → 이미 새 값이므로 skip

UPDATE POSTS SET CATEGORY = '스트레스' WHERE CATEGORY = '스트레스 관리';

UPDATE POSTS SET CATEGORY = '일상·기타'
WHERE CATEGORY IN ('경험 공유', '함께 해요', '질문과 답변', '추천 및 후기');

COMMIT;
