ALTER SESSION SET NLS_LENGTH_SEMANTICS=CHAR;

DECLARE
  c NUMBER;
BEGIN
  SELECT COUNT(*) INTO c FROM user_tables WHERE table_name = 'CARE_REPORTS';
  IF c = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE care_reports (
        id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id       NUMBER             NOT NULL,
        snapshot_json CLOB,
        letter_body   CLOB               NOT NULL,
        risk_level    VARCHAR2(20 CHAR)  DEFAULT 'NORMAL' NOT NULL,
        themes        VARCHAR2(500 CHAR),
        created_at    TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
        CONSTRAINT fk_care_reports_user
          FOREIGN KEY (user_id) REFERENCES users(id),
        CONSTRAINT chk_care_reports_risk
          CHECK (risk_level IN ('NORMAL', 'ELEVATED', 'CRISIS'))
      )
    ]';
  END IF;
END;
/

