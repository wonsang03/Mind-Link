-- 인덱스 — 24시간 한도 검사와 사용자별 최신순 조회를 빠르게
DECLARE
  c NUMBER;
BEGIN
  SELECT COUNT(*) INTO c FROM user_indexes WHERE index_name = 'IDX_CARE_REPORTS_USER_CREATED';
  IF c = 0 THEN
    EXECUTE IMMEDIATE 'CREATE INDEX idx_care_reports_user_created ON care_reports (user_id, created_at)';
  END IF;

END;
/

COMMIT;

