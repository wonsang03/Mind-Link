  -- 30 페르소나 × 7 명 = 210 row 적재
  ----------------------------------------------------------------------------
  FOR i IN 1 .. arr.COUNT LOOP
    FOR v IN 1 .. 7 LOOP
      v_s := ROUND(GREATEST(0, LEAST(C_S_MAX, arr(i).s + DBMS_RANDOM.VALUE(-2.5, 2.5))));
      v_d := ROUND(GREATEST(0, LEAST(C_D_MAX, arr(i).d + DBMS_RANDOM.VALUE(-2.5, 2.5))));
      v_a := ROUND(GREATEST(0, LEAST(C_A_MAX, arr(i).a + DBMS_RANDOM.VALUE(-2.5, 2.5))));

      v_norm_s := ROUND(v_s / C_S_MAX, 4);
      v_norm_d := ROUND(v_d / C_D_MAX, 4);
      v_norm_a := ROUND(v_a / C_A_MAX, 4);

      INSERT INTO user_assessment_profiles (
        user_id, persona_key, persona_label, persona_story,
        stress_score, depression_score, anxiety_score,
        stress_norm, depression_norm, anxiety_norm,
        cluster_id, is_synthetic, created_at, updated_at
      ) VALUES (
        NULL, arr(i).k, arr(i).lbl, arr(i).story,
        v_s, v_d, v_a,
        v_norm_s, v_norm_d, v_norm_a,
        arr(i).cid, 1, SYSTIMESTAMP, SYSTIMESTAMP
      );
    END LOOP;
  END LOOP;
END;
/

COMMIT;

