-- =============================================================================
-- §1. user_assessment_profiles
-- =============================================================================
DECLARE
  c NUMBER;
BEGIN
  SELECT COUNT(*) INTO c FROM user_tables WHERE table_name = 'USER_ASSESSMENT_PROFILES';
  IF c = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE user_assessment_profiles (
        id                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id           NUMBER,                                  -- 실사용자면 users.id, 합성이면 NULL
        persona_key       VARCHAR2(40 CHAR)  NOT NULL,             -- 페르소나 식별자(스네이크)
        persona_label     VARCHAR2(80 CHAR)  NOT NULL,             -- 한국어 라벨
        persona_story     VARCHAR2(500 CHAR),                      -- 2~3 문장 소개
        stress_score      NUMBER(5,1)        NOT NULL,             -- 원점수 (PSS 만점 40)
        depression_score  NUMBER(5,1)        NOT NULL,             -- 원점수 (PHQ-9 만점 27)
        anxiety_score     NUMBER(5,1)        NOT NULL,             -- 원점수 (GAD-7 만점 21)
        stress_norm       NUMBER(6,4)        NOT NULL,             -- 0~1
        depression_norm   NUMBER(6,4)        NOT NULL,             -- 0~1
        anxiety_norm      NUMBER(6,4)        NOT NULL,             -- 0~1
        cluster_id        NUMBER(3),                               -- K-Means 결과 (nullable)
        is_synthetic      NUMBER(1)          DEFAULT 1 NOT NULL,   -- 1=합성, 0=실사용자
        created_at        TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
        updated_at        TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
        CONSTRAINT chk_uap_synthetic CHECK (is_synthetic IN (0,1)),
        CONSTRAINT chk_uap_stress    CHECK (stress_score BETWEEN 0 AND 40),
        CONSTRAINT chk_uap_depress   CHECK (depression_score BETWEEN 0 AND 27),
        CONSTRAINT chk_uap_anxiety   CHECK (anxiety_score BETWEEN 0 AND 21),
        CONSTRAINT chk_uap_norm_s    CHECK (stress_norm BETWEEN 0 AND 1),
        CONSTRAINT chk_uap_norm_d    CHECK (depression_norm BETWEEN 0 AND 1),
        CONSTRAINT chk_uap_norm_a    CHECK (anxiety_norm BETWEEN 0 AND 1)
      )
    ]';
  END IF;
END;
/

-- 실사용자 1인 1행 보장 (NULL 은 무제한 중복 허용 — 합성에는 영향 없음)
DECLARE
  c NUMBER;
BEGIN
  SELECT COUNT(*) INTO c FROM user_indexes WHERE index_name = 'UQ_UAP_USER';
  IF c = 0 THEN
    EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX uq_uap_user ON user_assessment_profiles (user_id)';
  END IF;
END;
/

-- 참고: 클러스터 기반 "비슷한 마음 모임"(매칭방) 테이블은 향후 예비 기능으로,
--       현재 Java 코드에서 사용하지 않아 DDL 을 두지 않습니다(생성 시 clustering_rooms 등으로 별도 정의 예정).

-- =============================================================================
-- §2. 인덱스
-- =============================================================================
DECLARE
  c NUMBER;
BEGIN
  SELECT COUNT(*) INTO c FROM user_indexes WHERE index_name = 'IDX_UAP_CLUSTER';
  IF c = 0 THEN
    EXECUTE IMMEDIATE 'CREATE INDEX idx_uap_cluster ON user_assessment_profiles (cluster_id)';
  END IF;

  SELECT COUNT(*) INTO c FROM user_indexes WHERE index_name = 'IDX_UAP_PERSONA';
  IF c = 0 THEN
    EXECUTE IMMEDIATE 'CREATE INDEX idx_uap_persona ON user_assessment_profiles (persona_key)';
  END IF;
END;
/

