-- ① 총 210건
SELECT COUNT(*) AS total_rows FROM user_assessment_profiles WHERE is_synthetic = 1;

-- ② 페르소나별 평균 좌표 (30 행, cnt=7 each)
SELECT persona_key,
       COUNT(*)                          AS cnt,
       ROUND(AVG(stress_norm),3)         AS avg_s,
       ROUND(AVG(depression_norm),3)     AS avg_d,
       ROUND(AVG(anxiety_norm),3)        AS avg_a
FROM   user_assessment_profiles
WHERE  is_synthetic = 1
GROUP BY persona_key
ORDER BY persona_key;

-- ③ 시드 집단별 인원·중심좌표 (6 행)
SELECT cluster_id,
       COUNT(*)                          AS members,
       ROUND(AVG(stress_norm),3)         AS centroid_s,
       ROUND(AVG(depression_norm),3)     AS centroid_d,
       ROUND(AVG(anxiety_norm),3)        AS centroid_a
FROM   user_assessment_profiles
WHERE  is_synthetic = 1
GROUP BY cluster_id
ORDER BY cluster_id;

-- ④ 샘플 20건 (집단별 정렬)
